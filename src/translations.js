const TRANSLATION_ENTRIES = Object.entries(SPANISH_TRANSLATIONS)
	.sort(([left], [right]) => right.length - left.length);
const TRANSLATION_PATTERN = new RegExp(
	TRANSLATION_ENTRIES.map(([english]) => english.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"),
	"g"
);

export function translateSpanishText(value) {
	const protectedBrands = value
		.replaceAll("Apple Pay", "__PITZ_APPLE_PAY__")
		.replaceAll("Google Pay", "__PITZ_GOOGLE_PAY__")
		.replaceAll("● Pay", "__PITZ_APPLE_BADGE__")
		.replaceAll("G Pay", "__PITZ_GOOGLE_BADGE__");
	return protectedBrands.replace(TRANSLATION_PATTERN, (english) => SPANISH_TRANSLATIONS[english])
		.replaceAll("__PITZ_APPLE_PAY__", "Apple Pay")
		.replaceAll("__PITZ_GOOGLE_PAY__", "Google Pay")
		.replaceAll("__PITZ_APPLE_BADGE__", "● Pay")
		.replaceAll("__PITZ_GOOGLE_BADGE__", "G Pay");
}
